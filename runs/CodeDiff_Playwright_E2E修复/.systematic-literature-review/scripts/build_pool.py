def main():
    papers_path = ROOT / "papers.jsonl"
    scored_path = ROOT / "scored_papers.jsonl"
    selected_path = ROOT / "selected_papers.jsonl"
    with papers_path.open("w", encoding="utf-8") as fp, \
         scored_path.open("w", encoding="utf-8") as fs, \
         selected_path.open("w", encoding="utf-8") as fsel:
        for (pid, key, title, authors, year, venue, typ, doi, url, score, subtopic, abstract) in P:
            rec = {
                "id": pid, "key": key, "title": title,
                "authors": [a.strip() for a in authors.split(" and ")],
                "year": year, "venue": venue, "type": typ,
                "doi": doi, "url": url,
                "abstract": abstract,
            }
            fp.write(json.dumps(rec, ensure_ascii=False) + "\n")
            scored = dict(rec)
            scored.update({"score": score, "subtopic": subtopic,
                           "alignment": "high" if score >= 8 else ("mid" if score >= 6 else "low"),
                           "rationale": abstract[:60]})
            fs.write(json.dumps(scored, ensure_ascii=False) + "\n")
            # 全部选入（66 篇落在 standard 档 50-90 区间）
            fsel.write(json.dumps(scored, ensure_ascii=False) + "\n")
    print(f"papers={len(P)} -> {papers_path}")
    print(f"scored -> {scored_path}")
    print(f"selected -> {selected_path}")

if __name__ == "__main__":
    main()
