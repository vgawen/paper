// tldraw examples：写入覆盖复跑专用的 Playwright / Vite 配置（untracked，不修改项目代码）。
// 用 Vite dev（而非项目默认的 preview 生产构建），让 CDP 覆盖能看到源 URL；
// Vite 包装配置额外 dedupe react/react-dom——filtered pnpm 安装会让 workspace
// 包与 apps/examples 各持一份 React，浏览器侧会因双 React 报 useRef null。
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const appDir = path.resolve(here, '../../real/tldraw/apps/examples');
const cfgDir = path.join(appDir, 'e2e');

const viteCfg = `// AUTO-GENERATED by experiments/real/init_tldraw_cov.mjs — untracked.
// dedupe: the filtered pnpm install links workspace packages' react/react-dom
// to the global virtual store while apps/examples uses node_modules/.pnpm, so
// the browser otherwise loads two React copies (react-intl useRef on null).
import { mergeConfig, type ConfigEnv, type UserConfig, type UserConfigFn } from 'vite'
import base from './vite.config'

export default (env: ConfigEnv): UserConfig => {
	const cfg = base as unknown as UserConfigFn
	const resolved = typeof cfg === 'function' ? cfg(env) : cfg
	return mergeConfig(resolved, {
		resolve: {
			dedupe: ['react', 'react-dom', 'react/jsx-runtime', 'react/jsx-dev-runtime'],
		},
	})
}
`;

const cfg = `import path from 'node:path'
import { defineConfig, devices } from '@playwright/test'

const __dirname = path.dirname(new URL(import.meta.url).pathname)

// AUTO-GENERATED by experiments/real/init_tldraw_cov.mjs
// 覆盖采集专用：只起 Vite dev（5420，加载 dedupe 包装配置），不含 bemo-worker；
// 不改变项目内任何 tracked 文件。
export default defineConfig({
  testDir: './tests',
  timeout: 30 * 1000,
  expect: { timeout: 2000 },
  fullyParallel: false,
  retries: 0,
  reporter: 'list',
  use: {
    baseURL: 'http://localhost:5420',
    trace: 'off',
    headless: true,
    video: 'off',
    screenshot: 'off',
  },
  projects: [{ name: 'chromium', use: { ...devices['Desktop Chrome'] } }],
  outputDir: './__cov_test-results',
  webServer: {
    command: 'node_modules/.bin/vite --host --config vite.cov.config.ts',
    port: 5420,
    reuseExistingServer: false,
    cwd: path.join(__dirname, '..'),
    timeout: 300_000,
  },
})
`;
fs.mkdirSync(cfgDir, { recursive: true });
fs.writeFileSync(path.join(appDir, 'vite.cov.config.ts'), viteCfg);
fs.writeFileSync(path.join(cfgDir, '__cov_playwright.config.ts'), cfg);
console.log(`wrote ${path.join(cfgDir, '__cov_playwright.config.ts')} and vite.cov.config.ts`);
